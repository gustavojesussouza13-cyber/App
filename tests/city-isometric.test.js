 const p=client.worldPlayer;p.x=768;p.y=512;p.save.coins=15000;
 world.guild(p,{action:'create',name:'Reino dos Campos'});
 const act=(data,now=1000)=>politics.action(world,p,data,{walkable:()=>true,portals:[],npcs:[],now});
