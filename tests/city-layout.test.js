'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const layout=require('../public/city-layout');
test('mapa 3D da guilda utiliza 26x26 e libera antigas ruas',()=>{
 assert.equal(layout.N,26);
 assert.equal(layout.canPlace([],'house',5,5),true);
 assert.equal(layout.canPlace([],'house',5,12),true);
 assert.equal(layout.canPlace([],'market',20,20),true);
 assert.equal(layout.canPlace([],'tower',0,0),true);
 assert.equal(layout.canPlace([],'tower',25,25),false);
 assert.equal(layout.canPlace([],'house',24,24),true);
 assert.equal(layout.canPlace([],'house',25,24),false);
});
test('somente fortaleza central e construções ocupam o terreno, inclusive footprints',()=>{
 assert.deepEqual(layout.CORE,{x:11,y:11,w:4,h:4});
 assert.deepEqual(layout.size(layout.plan('house',1,1)),[2,2]);
 assert.deepEqual(layout.size(layout.plan('farm',1,1)),[3,3]);
 assert.deepEqual(layout.size(layout.plan('barracks',1,1)),[4,3]);
 assert.deepEqual(layout.size(layout.plan('tower',1,1)),[2,2]);
 assert.deepEqual(layout.size(layout.plan('market',1,1)),[3,2]);
 assert.equal(layout.canPlace([],'barracks',10,10),false,'invasão parcial do castelo');
 assert.equal(layout.canPlace([],'market',10,14),false,'invasão parcial do castelo');
 assert.equal(layout.canPlace([],'farm',16,16),true);
 const barracks=layout.plan('barracks',16,16);
 assert.equal(layout.at([barracks],19,18),barracks);
 assert.equal(layout.canPlace([barracks],'house',18,17),false);
 assert.equal(layout.canPlace([barracks],'house',20,16),true);
 assert.equal(layout.canPlace([],'unknown',3,3),false);
 assert.equal(layout.canPlace([],'house',NaN,3),false);
 assert.equal(layout.canPlace([],'house',3.1,3),false);
});
test('cidades históricas ficam no mesmo lugar, tamanho 1x1 e sem migração destrutiva',()=>{
 const old={type:'barracks',x:2,y:2};
 assert.deepEqual(layout.size(old),[1,1]);
 assert.equal(layout.at([old],2,2),old);
 assert.equal(layout.canPlace([old],'house',3,2),true);
 assert.equal(layout.canPlace([old],'house',2,2),false);
 const oldMulticell={type:'market',x:8,y:7,w:2,h:1};
 assert.deepEqual(layout.size(oldMulticell),[2,1]);
 assert.equal(layout.canPlace([oldMulticell],'house',9,7),false);
});
test('servidor compartilha layout seguro, cliente 3D carrega Three local e mundo permanece 2D',()=>{
 const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
 const server=read('kingdom-politics.js'),html=read('public/mundo.html');
 const client=read('public/guild-city-3d.js'),render=read('public/guild-scene-3d.mjs');
 assert.match(server,/cityLayout\.canPlace/);
 assert.match(client,/layout\.canPlace/);
 assert.match(html,/city-layout\.js/);
 assert.match(html,/guild-city-3d\.js/);
 assert.match(render,/WebGLRenderer/);
 assert.match(render,/vendor\/three\.module\.js/);
 assert.match(read('server.js'),/vendor\/three\.module\.js/);
 assert.match(read('public/mmo.js'),/const cityUI=window\.PeregrinosCity\.create/);
});
